export function t(lang, key) {
  return T[lang]?.[key] ?? T.es?.[key] ?? key
}

export function tFmt(lang, key, params) {
  let str = t(lang, key)
  Object.entries(params).forEach(([k, v]) => { str = str.replace(`{${k}}`, v) })
  return str
}

